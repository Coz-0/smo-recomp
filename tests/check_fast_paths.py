"""Check two fast paths of the runtime against the plain code they replaced, on random input.

    python tests/check_fast_paths.py

- index_max (runtime/gfx/nvn_vk_draw.c): the largest index of an index range, 16 bytes at a time (SSE2), against a loop
  over every index; 8-, 16- and 32-bit indices, primitive restart on and off.
- The live-list cell index (runtime/gfx/nvn_gl.c): job_list_overwrite looks only at the lists in the 64 KB chunks of
  command memory a new recording covers; checked against a walk over every live list (the same lists must end), and
  no dropped list may stay in the index.

The functions are copied out of the runtime sources into build/tmp/fast_paths_extract.h, so the code under test is the
runtime's own; tests/fast_paths.c holds the reference code and the random cases. Built with clang 9 at -O1, as the
runtime is. Exit status 0 when everything matches.
"""
import os
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RT = os.path.join(REPO, 'runtime', 'gfx')
TMP = os.path.join(REPO, 'build', 'tmp')
CLANG = os.path.join(os.environ.get('LLVM_ROOT', 'C:/llvm-9.0.0'), 'bin', 'clang.exe')


def cut(text, start, end, what):
    i = text.find(start)
    j = text.find(end, i + 1) if i >= 0 else -1
    if i < 0 or j < 0:
        sys.exit('check_fast_paths: %s not found in the runtime sources (did the code move?)' % what)
    return text[i:j]


def main():
    gl = open(os.path.join(RT, 'nvn_gl.c'), encoding='utf-8').read()
    vk = open(os.path.join(RT, 'nvn_vk_draw.c'), encoding='utf-8').read()
    parts = [
        '/* generated by tests/check_fast_paths.py from runtime/gfx/nvn_gl.c and runtime/gfx/nvn_vk_draw.c: do not edit */\n',
        cut(gl, 'typedef struct { uint8_t *data; size_t len;', '\n', 'the List record') + '\n',
        'static List *g_lists;\n'
        'static int g_list_count, *g_live, g_live_n;\n'
        'static LONG64 g_list_reuse_drops, g_list_reuse_events, g_imax_scans;\n'
        'static LONG64 g_imax_written;\n'
        'static uint32_t g_wlog_n;      /* no host writes in this check: a cached range is never written since */\n'
        'static int wlog_overlap(uint32_t from, uint64_t lo, uint64_t hi) { (void)from; (void)lo; (void)hi; return 0; }\n'
        'static SRWLOCK g_list_lock = SRWLOCK_INIT;\n'
        'static struct { uint32_t gen; int restart; } R;\n'
        'static uint8_t *g_mem;\n'
        '#define P(a) ((void *)(g_mem + (a)))\n',
        cut(gl, '#define CELL_SHIFT', '\nstatic CmdBuf *cb_get', 'the cell index') + '\n',
        cut(gl, 'typedef struct { uint64_t seg[4][3]; int nseg; LONG64 seq; } Overwrite;', 'static int list_lru_cmp',
            'job_list_overwrite') + '\n',
        cut(vk, 'static uint32_t index_max(uint64_t addr, int count, unsigned t) {', '/* maxv: the highest vertex',
            'index_max') + '\n',
    ]
    os.makedirs(TMP, exist_ok=True)
    with open(os.path.join(TMP, 'fast_paths_extract.h'), 'w', encoding='utf-8') as f:
        f.write(''.join(parts))
    exe = os.path.join(TMP, 'fast_paths.exe')
    r = subprocess.run([CLANG, '-O1', '-w', '-I', TMP, os.path.join(REPO, 'tests', 'fast_paths.c'), '-o', exe],
                       capture_output=True, text=True)
    if r.returncode:
        print((r.stdout + r.stderr)[-4000:])
        sys.exit('check_fast_paths: build failed')
    r = subprocess.run([exe])
    print('PASS' if r.returncode == 0 else 'FAIL')
    sys.exit(r.returncode)


if __name__ == '__main__':
    main()

"""Check the runtime's Yaz0 decoders (runtime/game/smo_yaz0.c) against the game's own, lifted, on every .szs of the RomFS.

    python tests/check_yaz0.py [--every N] [--seed S]

The game's two decoders (sead's SZSDecompressor::streamDecomp and its whole-buffer decoder) are found the way the
lifter's patch finds them (tools/lifter/game_patches.py) and lifted without that patch (recomp.py lift) into
build/tmp/yaz0_lifted.c; the decoders are copied out of the runtime source into build/tmp/yaz0_extract.h, so the code
under test is the runtime's own. Both are built as the game is (clang -O2, LLVM_ROOT); tests/yaz0.c runs them on each
file, whole and in random chunks, and compares every answer, the context after every chunk and the output; then times
both. --every N: one file in N (a quicker run).
Exit status 0 when nothing differs.
"""
import argparse
import glob
import os
import re
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, 'tools'))
sys.path.insert(0, os.path.join(REPO, 'tools', 'lifter'))
import target as T  # noqa: E402
import recomp  # noqa: E402
import game_patches  # noqa: E402

TMP = T.build('tmp')
CLANG = os.path.join(os.environ.get('LLVM_ROOT', 'C:/llvm-9.0.0'), 'bin', 'clang.exe')


def cut(text, start, end, what):
    i = text.find(start)
    j = text.find(end, i + 1) if i >= 0 else -1
    if i < 0 or j < 0:
        sys.exit('check_yaz0: %s not found in the runtime sources (did the code move?)' % what)
    return text[i:j]


def body(text, addr, name):
    """The lifted function at addr out of recomp.py's output, renamed."""
    m = re.search(r'^void f_%x\(Ctx \*c\) \{\n.*?^\}\n' % addr, text, re.S | re.M)
    if not m:
        sys.exit('check_yaz0: f_%x not in the lifted output' % addr)
    return m.group(0).replace('void f_%x(Ctx *c)' % addr, 'void %s(Ctx *c)' % name, 1)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--every', type=int, default=1, help='one file in N')
    ap.add_argument('--seed', default='1')
    a = ap.parse_args()
    found = game_patches.find_funcs(recomp.word, recomp.BASE, recomp.TEXT_SIZE)
    if set(found) != {'yaz0_stream', 'yaz0_whole'}:
        sys.exit('check_yaz0: the game\'s Yaz0 decoders were not found')
    os.makedirs(TMP, exist_ok=True)
    raw = os.path.join(TMP, 'yaz0_lifted_raw.c')
    r = subprocess.run([sys.executable, os.path.join(REPO, 'tools', 'lifter', 'recomp.py'), 'lift', raw,
                        '%x,%x' % (found['yaz0_stream'], found['yaz0_whole'])], capture_output=True, text=True)
    if r.returncode:
        sys.exit(r.stdout + r.stderr)
    text = open(raw).read()
    stream, whole = body(text, found['yaz0_stream'], 'f_yaz0_stream'), body(text, found['yaz0_whole'], 'f_yaz0_whole')
    called = sorted(set(re.findall(r'\bf_([0-9a-f]+)\(c\);', stream + whole)))
    with open(os.path.join(TMP, 'yaz0_lifted.c'), 'w') as f:
        f.write('/* generated by tests/check_yaz0.py: do not edit */\n#include "runtime.h"\n\n')
        for n in called:       # only the dead fall past the end of the hand-written decoder
            f.write('void f_%s(Ctx *c) { (void)c; guest_trap("fell out of a Yaz0 decoder", 0x%sULL); }\n' % (n, n))
        f.write(stream + '\n' + whole)
    pages = sorted({int(p, 16) for p in re.findall(r'\(uint64_t\)\(0x([0-9a-f]+000)ULL\)', stream + whole)})
    with open(os.path.join(TMP, 'yaz0_pages.h'), 'w') as f:
        f.write('/* generated by tests/check_yaz0.py: do not edit */\nstatic const struct { uint64_t addr; uint8_t data[4096]; } yaz0_pages[] = {\n')
        for p in pages:
            data = bytes(recomp.IMG[recomp.FILE_OFF + p - recomp.BASE + i] if 0 <= recomp.FILE_OFF + p - recomp.BASE + i < len(recomp.IMG) else 0
                         for i in range(4096))
            f.write('  { 0x%xULL, {%s} },\n' % (p, ','.join(str(b) for b in data)))
        f.write('};\n')
    src = open(os.path.join(REPO, 'runtime', 'game', 'smo_yaz0.c'), encoding='utf-8').read()
    with open(os.path.join(TMP, 'yaz0_extract.h'), 'w', encoding='utf-8') as f:
        f.write('/* generated by tests/check_yaz0.py from runtime/game/smo_yaz0.c: do not edit */\n'
                + cut(src, '/* sead::SZSDecompressor::DecompContext', "/* The lifter's patches", 'the decoders'))
    exe = os.path.join(TMP, 'yaz0_check.exe')
    flags = ['-O2', '-w', '-fno-strict-aliasing', '-ffp-contract=off', '-I', TMP] + T.runtime_includes()
    r = subprocess.run([CLANG, *flags, os.path.join(REPO, 'tests', 'yaz0.c'), os.path.join(TMP, 'yaz0_lifted.c'),
                        '-o', exe], capture_output=True, text=True)
    if r.returncode:
        print((r.stdout + r.stderr)[-4000:])
        sys.exit('check_yaz0: build failed')
    files = sorted(glob.glob(os.path.join(T.build('romfs'), '**', '*.szs'), recursive=True))[::a.every]
    if not files:
        sys.exit('check_yaz0: no .szs under %s' % T.build('romfs'))
    lst = os.path.join(TMP, 'yaz0_files.txt')
    with open(lst, 'w', encoding='utf-8') as f:
        f.write('\n'.join(files) + '\n')
    r = subprocess.run([exe, lst, a.seed])
    print('PASS' if r.returncode == 0 else 'FAIL')
    sys.exit(r.returncode)


if __name__ == '__main__':
    main()

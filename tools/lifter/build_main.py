"""Compile the lifted main (build/lift/main/*.c) with clang into objects.

    python tools/lifter/build_main.py [jobs] [--force]

Flags and the bounded-time rule are ssbu-recomp's (tools/lifter/build_opt.py, GPL-3.0-or-later):
  clang 9, -O1 -w -fno-strict-aliasing -ffp-contract=off (no fused multiply-add is formed; fused operations the game
  asks for are explicit fma() calls), default x86-64 target; on macOS Apple clang, arm64 (tools/target.py), where
  -ffp-contract=off matters more: clang contracts by default for AArch64;
  1. every function longer than OPTNONE_LINES statements is compiled unoptimised (`optnone`, through a generated
     -include header; the generated C is untouched);
  2. a file over TIME_LIMIT seconds is retried with the statement limit divided by 4, then 16;
  3. then the whole file at -O0.
Only files whose object is missing or older than the source (or funcs.h / runtime headers) are compiled.
Prints counts, fallbacks and the slowest files; writes build/obj/main/_report.txt. Exit code 1 if any file fails.
Environment: LLVM_ROOT (default C:/llvm-9.0.0; macOS: Apple clang), RECOMP_OPT (-O2), RECOMP_OPTNONE_LINES (20000), RECOMP_TIME_LIMIT (180),
RECOMP_ARCH (extra target flags, e.g. -march=znver2; the objects then run on that CPU family and later ones only).
A change of these does not recompile by itself: run with --force.
"""
import concurrent.futures
import os
import re
import subprocess
import sys
import time

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(REPO, 'tools'))
import target as T  # noqa: E402
GEN = T.build('lift', 'main')
OBJ = T.build('obj', 'main')
RUNTIME = os.path.join(T.RUNTIME, 'core')        # runtime.h, neon.h, fpexact.h: what the lifted C includes
CLANG = T.clang()
OPT = os.environ.get('RECOMP_OPT', '-O2')       # -O2: New Donk City 20 -> 30-36 fps against -O1 (Ryzen 5 3600XT)
EXTRA = ['-ffp-contract=off'] + os.environ.get('RECOMP_ARCH', '').split()   # e.g. RECOMP_ARCH=-march=znver2: this PC's CPU only
OPTNONE_LINES = int(os.environ.get('RECOMP_OPTNONE_LINES', '20000'))
TIME_LIMIT = float(os.environ.get('RECOMP_TIME_LIMIT', '180'))
BASE_FLAGS = ['-w', '-fno-strict-aliasing', '-I', RUNTIME, '-I', GEN]
DEF = re.compile(r'^(?:static )?void (\w+)\((Ctx \*c(?:, uint64_t rp)?)\) \{$')


def function_sizes(path):
    out, cur, n = [], None, 0
    with open(path, encoding='latin-1') as f:
        for line in f:
            if cur is None:
                m = DEF.match(line.rstrip('\n'))
                if m:
                    cur, n = (m.group(1), m.group(2)), 0
            elif line.startswith('}'):
                out.append((n, cur[0], cur[1]))
                cur = None
            else:
                n += 1
    return out


def optnone_header(src, obj, limit):
    big = [(n, name, params) for n, name, params in function_sizes(src) if n > limit]
    path = os.path.splitext(obj)[0] + '.optnone.h'
    if not big:
        if os.path.exists(path):
            os.remove(path)
        return None, 0, 0
    with open(path, 'w') as f:
        f.write('/* generated by build_main.py: functions too long to optimise in bounded time */\n#include "runtime.h"\n')
        for n, name, params in big:
            f.write('void %s(%s) __attribute__((optnone, noinline));\n' % (name, params))
    return path, len(big), sum(b[0] for b in big)


def run_limited(cmd, limit):
    t = time.time()
    p = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    try:
        out, _ = p.communicate(timeout=limit)
        return p.returncode, out.decode('latin-1')[-3000:], time.time() - t
    except subprocess.TimeoutExpired:
        if T.MAC:
            p.kill()
        else:
            subprocess.run(['taskkill', '/PID', str(p.pid), '/T', '/F'], capture_output=True)
        p.communicate()
        return None, '', time.time() - t


def compile_file(name):
    src = os.path.join(GEN, name)
    obj = os.path.join(OBJ, name[:-2] + T.OBJ_EXT)
    total = 0.0
    for step, limit in enumerate((OPTNONE_LINES, OPTNONE_LINES // 4, OPTNONE_LINES // 16)):
        hdr, count, lines = optnone_header(src, obj, limit)
        if step and not count:
            continue
        cmd = [CLANG, '-c', OPT] + EXTRA + BASE_FLAGS + (['-include', hdr] if hdr else []) + [src, '-o', obj]
        code, out, secs = run_limited(cmd, TIME_LIMIT)
        total += secs
        if code is not None:
            note = ('%d function(s) over %d statements unoptimised (%d statements)' % (count, limit, lines)) if count else ''
            return name, code, out, total, note
    cmd = [CLANG, '-c', '-O0'] + EXTRA + BASE_FLAGS + [src, '-o', obj]
    t = time.time()
    r = subprocess.run(cmd, capture_output=True, text=True)
    return name, r.returncode, (r.stdout + r.stderr)[-3000:], total + time.time() - t, \
        'WHOLE FILE at -O0 (time limit %.0fs exceeded three times)' % TIME_LIMIT


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    jobs = int(args[0]) if args else max(1, (os.cpu_count() or 8) - 4)
    force = '--force' in sys.argv
    os.makedirs(OBJ, exist_ok=True)
    deps = [os.path.join(GEN, 'funcs.h')] + [os.path.join(RUNTIME, h) for h in ('runtime.h', 'neon.h', 'fpexact.h')]
    newest_dep = max(os.path.getmtime(d) for d in deps)
    names = sorted(n for n in os.listdir(GEN) if n.endswith('.c'))
    todo = []
    for n in names:
        obj = os.path.join(OBJ, n[:-2] + T.OBJ_EXT)
        if force or not os.path.exists(obj) or os.path.getmtime(obj) < max(os.path.getmtime(os.path.join(GEN, n)), newest_dep):
            todo.append(n)
    print('files: %d   to compile: %d   jobs: %d   %s %s' % (len(names), len(todo), jobs, CLANG, OPT))
    t0 = time.time()
    results = []
    with concurrent.futures.ThreadPoolExecutor(jobs) as ex:
        for k, r in enumerate(ex.map(compile_file, sorted(todo, key=lambda n: -os.path.getsize(os.path.join(GEN, n))))):
            results.append(r)
            name, code, out, secs, note = r
            if code or note:
                print('  %s %s  %.0fs  %s' % ('FAIL' if code else 'note', name, secs, note))
                if code:
                    print('    ' + out.replace('\n', '\n    ')[-1500:])
            if (k + 1) % 25 == 0:
                print('  %d/%d done  (%.0fs)' % (k + 1, len(todo), time.time() - t0), flush=True)
    failed = [r for r in results if r[1]]
    noted = [r for r in results if r[4]]
    wall = time.time() - t0
    print('compiled %d files in %.0fs wall (%.0fs compiler time): %d failed, %d with a fallback'
          % (len(results), wall, sum(r[3] for r in results), len(failed), len(noted)))
    for name, code, out, secs, note in sorted(results, key=lambda r: -r[3])[:8]:
        print('  slowest: %-12s %6.0fs %s' % (name, secs, note))
    objs = [os.path.join(OBJ, n[:-2] + T.OBJ_EXT) for n in names]
    have = sum(1 for o in objs if os.path.exists(o))
    print('objects present: %d of %d   total size %.0f MB'
          % (have, len(objs), sum(os.path.getsize(o) for o in objs if os.path.exists(o)) / 2 ** 20))
    with open(os.path.join(OBJ, '_report.txt'), 'a') as f:
        f.write('# %s  %s %s  optnone over %d, limit %.0fs: %d compiled, %d failed, %.0fs wall\n'
                % (time.strftime('%Y-%m-%d %H:%M'), CLANG, OPT, OPTNONE_LINES, TIME_LIMIT, len(results), len(failed), wall))
        for name, code, out, secs, note in results:
            if code or note:
                f.write('%s\t%s\t%.0f\t%s\n' % (name, 'FAIL' if code else 'ok', secs, note))
    sys.exit(1 if failed or have != len(objs) else 0)


if __name__ == '__main__':
    main()

"""python tools/lifter/gen_sdktest.py  -> build/gen/sdktest_data.h : reference data for the host SDK self-test (SMO_SDK_SELFTEST=1).

Adapted from ssbu-recomp tools/lifter/gen_sdktest.py (GPL-3.0-or-later). Everything is independent of the game and of
sdk.elf: JPEG pictures made and decoded here with Pillow (libjpeg-turbo) -- SMO imports nn::image JPEG functions
(snapshot mode).
"""
import io
import os
import sys

from PIL import Image

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(REPO, 'tools'))
import target as T  # noqa: E402
OUT = T.build('gen', 'sdktest_data.h')

out = ['/* generated by tools/lifter/gen_sdktest.py -- reference data for the SDK self-test; do not edit */', '']


def carr(name, b):
    lines = ['static const uint8_t %s[%d] = {' % (name, max(len(b), 1))]
    for i in range(0, len(b), 24):
        lines.append('  ' + ','.join(str(x) for x in b[i:i + 24]) + ',')
    if not b:
        lines.append('  0,')
    lines.append('};')
    return lines


# ---- JPEG
def picture(w, h):
    im = Image.new('RGB', (w, h))
    px = im.load()
    for y in range(h):
        for x in range(w):
            px[x, y] = ((x * 255) // (w - 1), (y * 255) // (h - 1), ((x + y) * 255) // (w + h - 2))
    return im


jout = []
for name, w, h, sub in (('j420', 24, 16, 2), ('j444', 19, 13, 0), ('j422', 32, 8, 1)):
    buf = io.BytesIO()
    picture(w, h).save(buf, 'JPEG', quality=92, subsampling=sub)
    data = buf.getvalue()
    dec = Image.open(io.BytesIO(data)).convert('RGB')
    out += carr('jpeg_%s' % name, data) + carr('jpeg_%s_rgb' % name, dec.tobytes())
    jout.append('  {"%s", jpeg_%s, %d, jpeg_%s_rgb, %d, %d},' % (name, name, len(data), name, w, h))
out.append('static const struct { const char *name; const uint8_t *data; unsigned size; const uint8_t *rgb; int width, height; } jvecs[] = {')
out += jout
out.append('};')
os.makedirs(os.path.dirname(OUT), exist_ok=True)
text_out = '\n'.join(out) + '\n'
if not os.path.exists(OUT) or open(OUT).read() != text_out:
    open(OUT, 'w', newline='\n').write(text_out)
print('sdktest_data.h: %d jpegs' % len(jout))

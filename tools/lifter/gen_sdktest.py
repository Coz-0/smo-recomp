"""python tools/lifter/gen_sdktest.py  -> build/gen/sdktest_data.h : reference data for the host SDK self-test (SMO_SDK_SELFTEST=1).

Adapted from ssbu-recomp tools/lifter/gen_sdktest.py (GPL-3.0-or-later). Everything is independent of the game and of
sdk.elf:
  * deflate streams: made here with Python's zlib;
  * JPEG: made and decoded here with Pillow (libjpeg-turbo)  -- SMO imports nn::image JPEG functions (snapshot mode).
SMO imports no nn::mii function, so the Mii reference (which ssbu-recomp read from a yuzu-family checkout) is not
generated: MII_REFERENCE_AVAILABLE is 0 and the Mii part of the self-test reports itself as skipped.
"""
import io
import os
import random
import zlib

from PIL import Image

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(REPO, 'build', 'gen', 'sdktest_data.h')

out = ['/* generated by tools/lifter/gen_sdktest.py -- reference data for the SDK self-test; do not edit */', '',
       '#define MII_REFERENCE_AVAILABLE 0     /* SMO imports no nn::mii function: no Mii reference data */',
       '#define MII_DEFAULT_COUNT 6',
       'static const uint32_t mii_default_raw[6][49] = {{0}};',
       'static const uint16_t mii_default_nick[6][10] = {{0}};',
       '#define MII_ACCESSOR_COUNT 1',
       'static const char *const mii_accessor_names[MII_ACCESSOR_COUNT] = { "" };',
       'static const uint8_t mii_accessor_expect[6][MII_ACCESSOR_COUNT] = {{0}};', '']


def carr(name, b):
    lines = ['static const uint8_t %s[%d] = {' % (name, max(len(b), 1))]
    for i in range(0, len(b), 24):
        lines.append('  ' + ','.join(str(x) for x in b[i:i + 24]) + ',')
    if not b:
        lines.append('  0,')
    lines.append('};')
    return lines


# ---- deflate vectors (identical construction to ssbu-recomp's)
rnd = random.Random(1234)
text = (b'The quick brown fox jumps over the lazy dog. ' * 40) + bytes(rnd.randrange(97, 123) for _ in range(700))
vecs = [
    ('text9', text, zlib.compress(text, 9)),
    ('stored', bytes(rnd.randrange(256) for _ in range(300)), None),
    ('runs', b''.join(bytes([i & 0xff]) * (i * 7 % 300 + 1) for i in range(120)), None),
    ('fixed', b'abcabcabcabc hello hello', None),
    ('empty', b'', None),
]
vout = []
for name, plain, comp in vecs:
    if comp is None:
        if name == 'stored':
            co = zlib.compressobj(0)
            comp = co.compress(plain) + co.flush()
        elif name == 'fixed':
            co = zlib.compressobj(9, zlib.DEFLATED, 15, 9, zlib.Z_FIXED)
            comp = co.compress(plain) + co.flush()
        else:
            comp = zlib.compress(plain, 6)
    assert zlib.decompress(comp) == plain
    out += carr('zvec_%s_plain' % name, plain) + carr('zvec_%s_comp' % name, comp)
    vout.append('  {"%s", zvec_%s_plain, %d, zvec_%s_comp, %d},' % (name, name, len(plain), name, len(comp)))
out.append('static const struct { const char *name; const uint8_t *plain; unsigned plain_size; const uint8_t *comp; unsigned comp_size; } zvecs[] = {')
out += vout
out.append('};')
bad = bytearray(zlib.compress(text, 9))
bad[40] ^= 0x55
bad[41] ^= 0xaa
out += carr('zvec_corrupt', bytes(bad))
out.append('#define ZVEC_CORRUPT_PLAIN_SIZE %d' % len(text))


# ---- JPEG
def picture(w, h):
    im = Image.new('RGB', (w, h))
    px = im.load()
    for y in range(h):
        for x in range(w):
            px[x, y] = ((x * 255) // (w - 1), (y * 255) // (h - 1), ((x + y) * 255) // (w + h - 2))
    return im


jout = []
for name, w, h, sub in (('j420', 24, 16, 2), ('j444', 19, 13, 0), ('j422', 32, 8, 1)):
    buf = io.BytesIO()
    picture(w, h).save(buf, 'JPEG', quality=92, subsampling=sub)
    data = buf.getvalue()
    dec = Image.open(io.BytesIO(data)).convert('RGB')
    out += carr('jpeg_%s' % name, data) + carr('jpeg_%s_rgb' % name, dec.tobytes())
    jout.append('  {"%s", jpeg_%s, %d, jpeg_%s_rgb, %d, %d},' % (name, name, len(data), name, w, h))
out.append('static const struct { const char *name; const uint8_t *data; unsigned size; const uint8_t *rgb; int width, height; } jvecs[] = {')
out += jout
out.append('};')
os.makedirs(os.path.dirname(OUT), exist_ok=True)
text_out = '\n'.join(out) + '\n'
if not os.path.exists(OUT) or open(OUT).read() != text_out:
    open(OUT, 'w', newline='\n').write(text_out)
print('sdktest_data.h: Mii reference not generated (SMO imports no nn::mii), %d deflate vectors, %d jpegs' % (len(vecs), len(jout)))
